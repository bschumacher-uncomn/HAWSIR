// Generates compliance/oscal-component.yaml from the control list the UI displays,
// so the compliance claim on the Edge screen and the OSCAL artifact cannot drift apart.
// usage: pnpm exec tsx ci/gen-oscal.ts
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTROLS } from '../src/data/platform';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VERSION = (JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')) as { version: string }).version;

const uuid = (seed: string) => {
  const h = createHash('sha1').update(`navifi:${seed}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 0x3) | 0x8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s: string) => JSON.stringify(s);
const indent = (s: string, n: number) => s.replace(/^/gm, ' '.repeat(n));

const VALIDATIONS = [
  {
    id: 'pods-nonroot',
    controls: ['AC-6', 'CM-7'],
    text: 'Every NAVIFI pod runs as non-root with all capabilities dropped',
    yaml: `metadata:
  name: navifi-pods-nonroot
  uuid: ${uuid('val:pods-nonroot')}
domain:
  type: kubernetes
  kubernetes-spec:
    resources:
      - name: pods
        resource-rule:
          version: v1
          resource: pods
          namespaces: [navifi]
provider:
  type: opa
  opa-spec:
    rego: |
      package validate
      import rego.v1
      default validate := false
      validate if {
        count(input.pods) > 0
        every pod in input.pods {
          pod.spec.securityContext.runAsNonRoot == true
          every c in pod.spec.containers {
            c.securityContext.allowPrivilegeEscalation == false
            "ALL" in c.securityContext.capabilities.drop
          }
        }
      }`,
  },
  {
    id: 'mesh-mtls',
    controls: ['SC-8', 'SC-23'],
    text: 'NAVIFI namespace is enrolled in the Istio mesh (mTLS) by UDS Core',
    yaml: `metadata:
  name: navifi-mesh-enrolled
  uuid: ${uuid('val:mesh-mtls')}
domain:
  type: kubernetes
  kubernetes-spec:
    resources:
      - name: ns
        resource-rule:
          version: v1
          resource: namespaces
          name: navifi
provider:
  type: opa
  opa-spec:
    rego: |
      package validate
      import rego.v1
      default validate := false
      validate if input.ns.metadata.labels["istio-injection"] == "enabled"
      validate if input.ns.metadata.labels["istio.io/dataplane-mode"] == "ambient"`,
  },
  {
    id: 'audit-pvc',
    controls: ['AU-9', 'AU-11'],
    text: 'Append-only audit volume exists and is bound',
    yaml: `metadata:
  name: navifi-audit-volume
  uuid: ${uuid('val:audit-pvc')}
domain:
  type: kubernetes
  kubernetes-spec:
    resources:
      - name: pvcs
        resource-rule:
          version: v1
          resource: persistentvolumeclaims
          namespaces: [navifi]
provider:
  type: opa
  opa-spec:
    rego: |
      package validate
      import rego.v1
      default validate := false
      validate if {
        some pvc in input.pvcs
        endswith(pvc.metadata.name, "-audit")
        pvc.status.phase == "Bound"
      }`,
  },
];

const reqs = CONTROLS.map((c) => {
  const links = VALIDATIONS.filter((v) => v.controls.includes(c.id));
  return `- uuid: ${uuid(`req:${c.id}`)}
  control-id: ${c.id.toLowerCase()}
  description: ${q(`${c.title}: ${c.by}`)}
  props:
    - name: implementation-status
      ns: https://docs.lula.dev/oscal/ns
      value: ${c.satisfied ? 'implemented' : 'planned'}${
        links.length
          ? `
  links:
${links.map((v) => `    - href: "#${uuid(`res:${v.id}`)}"\n      rel: lula\n      text: ${q(v.text)}`).join('\n')}`
          : ''
      }`;
}).join('\n');

const resources = VALIDATIONS.map(
  (v) => `- uuid: ${uuid(`res:${v.id}`)}
  title: ${q(v.text)}
  rlinks:
    - href: lula.dev
  description: |
${indent(v.yaml, 4)}`,
).join('\n');

const out = `# Generated by ci/gen-oscal.ts from src/data/platform.ts. Do not edit by hand.
# Validate: lula validate -f compliance/oscal-component.yaml
component-definition:
  uuid: ${uuid('component-definition')}
  metadata:
    title: NAVIFI on UDS Core
    last-modified: "2026-11-03T00:00:00Z"
    version: ${q(VERSION)}
    oscal-version: 1.1.2
  components:
    - uuid: ${uuid('component:navifi')}
      type: software
      title: NAVIFI
      description: Deterministic mission consequence engine, watch floor UI and tamper-evident audit, deployed on RHEL 9 + RKE2 + UDS Core.
      purpose: Shipboard readiness decision support (advisory; human in the loop)
      control-implementations:
        - uuid: ${uuid('impl:800-53r5')}
          source: https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json
          description: NIST SP 800-53 rev5 controls satisfied by NAVIFI together with inherited UDS Core and platform controls (${CONTROLS.filter((c) => c.satisfied).length}/${CONTROLS.length}).
          implemented-requirements:
${indent(reqs, 12)}
  back-matter:
    resources:
${indent(resources, 6)}
`;

fs.mkdirSync(path.join(root, 'compliance'), { recursive: true });
fs.writeFileSync(path.join(root, 'compliance', 'oscal-component.yaml'), out);
console.log(`wrote compliance/oscal-component.yaml · ${CONTROLS.length} controls · ${VALIDATIONS.length} Lula validations`);
